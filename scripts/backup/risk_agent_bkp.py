def add_calculated_dscr(records: list[dict], dscr_results: list[dict]) -> list[dict]:
    """Return copies of `records` with a `calculated_dscr` field added to each one.

    Records whose DSCR call failed or was skipped get `calculated_dscr: None`,
    so every record from valid_records.json is still present in the output.
    """
    dscr_by_id = {r["application_id"]: r.get("dscr") for r in dscr_results}
    return [
        {**record, "calculated_dscr": dscr_by_id.get(record.get("application_id"))}
        for record in records
    ]


def save_json(data, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
    print(f"\nSaved {len(data)} records -> {path}")


