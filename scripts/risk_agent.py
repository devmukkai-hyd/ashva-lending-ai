def tool_interest_currency_calculator(operation: str, amount: float,
                                      annual_rate_pct: float = None,
                                      tenor_months: int = None,
                                      currency: str = None) -> dict:
    if operation == "convert_currency":
        if not currency:
            raise ValueError("currency is required for convert_currency (e.g. USD, EUR).")
        code = currency.upper()
        fx = get_currency_rate(code)
        return {"amount": amount, "currency": code, "inr_per_unit": fx,
                "amount_inr": round(amount * fx, 2)}

    if operation == "convert_inr_to_currency":
        if not currency:
            raise ValueError("currency is required for convert_inr_to_currency (e.g. USD).")
        code = currency.upper()
        fx = get_currency_rate(code)          # INR per 1 unit of `code`, e.g. USD_INR
        return {"amount_inr": amount, "currency": code, "inr_per_unit": fx,
                "amount": round(amount / fx, 2)}

    if not tenor_months:
        raise ValueError("tenor_months is required for emi and simple_interest.")
    if annual_rate_pct is None:
        annual_rate_pct = get_assessment_rate_pct()

    if operation == "simple_interest":
        interest = amount * annual_rate_pct / 100 * tenor_months / 12
        return {"principal": amount, "annual_rate_pct": annual_rate_pct,
                "tenor_months": tenor_months, "interest": round(interest, 2)}

    if operation == "emi":
        r = annual_rate_pct / 12 / 100
        emi = amount / tenor_months if r == 0 else amount * r / (1 - (1 + r) ** (-tenor_months))
        return {"principal": amount, "annual_rate_pct": annual_rate_pct,
                "tenor_months": tenor_months, "monthly_emi": round(emi, 2),
                "annual_debt_service": round(emi * 12, 2)}

    raise ValueError(f"Unknown operation '{operation}'. Use emi, simple_interest, convert_currency or convert_inr_to_currency.")


