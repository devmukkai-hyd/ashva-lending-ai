def _unwrap_exception_group(exc):
    """anyio's TaskGroup (used by stdio_client and ClientSession) can wrap a failure in
    one or more layers of ExceptionGroup. Keep unwrapping .exceptions[0] until we reach
    something that isn't a group -- that's the actual root cause."""
    while hasattr(exc, "exceptions") and exc.exceptions:
        exc = exc.exceptions[0]
    return exc


def _tool_text(result):
    """Return the text payload of an MCP tool result, or raise if the tool reported an error."""
    text = result.content[0].text if result.content else None
    # Older MCP SDKs expose `isError`; newer ones use snake_case `is_error`.
    is_error = getattr(result, "is_error", None)
    if is_error is None:
        is_error = getattr(result, "isError", False)
    if is_error:
        raise RuntimeError(text or str(result))
    return text


def call_mcp_tool(command: str, args: list[str], tool_name: str, arguments: dict,
                  timeout: float = MCP_TIMEOUT_SECONDS):
    """Synchronous wrapper around ONE MCP tool call (starts and stops the server each time).

    Use this for one-off calls. For many calls, open a single session instead
    (see run_dscr_mcp_client below).
    Returns the tool's text result; raises if the server reports an error or times out.
    """
    async def _call():
        server_params = StdioServerParameters(command=command, args=args)
        # errlog=sys.stderr so server startup errors (e.g. missing fastmcp) are visible.
        async with stdio_client(server_params, errlog=sys.stderr) as (read, write):
            async with ClientSession(read, write) as session:
                await session.initialize()
                result = await session.call_tool(tool_name, arguments)
                return _tool_text(result)

    try:
        asyncio.get_running_loop()
    except RuntimeError:
        pass                    # normal script: no event loop running, asyncio.run below works
    else:
        # Called from inside a running event loop (Langfuse run_experiment, Jupyter): asyncio.run() is not
        # allowed there - it fails before the call even starts ("coroutine ... was never awaited") and the
        # DSCR silently goes missing. Run the same call in a worker thread, which has no loop of its own.
        from concurrent.futures import ThreadPoolExecutor
        with ThreadPoolExecutor(max_workers=1) as pool:
            return pool.submit(call_mcp_tool, command, args, tool_name, arguments, timeout).result()
    try:
        return asyncio.run(asyncio.wait_for(_call(), timeout=timeout))
    except BaseException as exc:  # noqa: BLE001
        raise _unwrap_exception_group(exc) from None


@lru_cache(maxsize=None)
def get_reference_rate(rate_name: str) -> float:
    """Fetch any reference rate (assessment_rate_pct, base_rate_pct, USD_INR, ...) from the rates
    MCP server (rate_mcp_server.py). Cached per run."""
    if not RATE_SERVER_PATH.exists():
        raise FileNotFoundError(f"{RATE_SERVER_PATH} not found. Run `python rate_server.py` first to generate it.")
    text = call_mcp_tool(PYTHON_BIN, [str(RATE_SERVER_PATH)], "get_rate", {"rate_name": rate_name})
    return float(json.loads(text)["value"])


def get_assessment_rate_pct() -> float:
    return get_reference_rate(ASSESSMENT_RATE_NAME)


def get_currency_rate(currency: str = "USD") -> float:
    """INR per unit of `currency`, from the rates MCP server (e.g. USD_INR)."""
    return get_reference_rate(f"{currency.upper()}_INR")


