def dscr_inputs(application: dict) -> dict:
    """calculate_dscr arguments for an intake record: EBITDA joined from applicants.json."""
    profile = _by_applicant("applicants.json").get(application.get("applicant_id"))
    if profile is None:
        raise KeyError(f"applicant {application.get('applicant_id')} not in applicants.json")
    return {
        "ebitda_inr": profile["ebitda_inr"],
        "requested_amount_inr": application["requested_amount_inr"],
        "requested_tenor_months": application["requested_tenor_months"],
        "existing_annual_debt_service_inr": application["existing_annual_debt_service_inr"],
    }


async def _run_dscr_for_all(applications: list[dict], assessment_rate_pct: float) -> list[dict]:
    params = StdioServerParameters(command=PYTHON_BIN, args=[str(DSCR_SERVER_PATH)])
    outputs = []

    async with stdio_client(params, errlog=sys.stderr) as (read, write):
        async with ClientSession(read, write) as session:
            await session.initialize()

            for application in applications:
                app_id = application.get("application_id", "<unknown>")
                try:
                    arguments = {**dscr_inputs(application), "assessment_rate_pct": assessment_rate_pct}
                except KeyError as e:
                    print(f"Skipped {app_id}: missing {e}")
                    continue

                try:
                    result = await asyncio.wait_for(
                        session.call_tool("calculate_dscr", arguments),
                        timeout=MCP_TIMEOUT_SECONDS,
                    )
                    dscr_result = json.loads(_tool_text(result))
                except Exception as e:  # tool error, timeout, bad JSON
                    print(f"Failed: {app_id} -> {_unwrap_exception_group(e)}")
                    continue

                print(f"Application: {app_id}  DSCR: {dscr_result.get('dscr')}")
                outputs.append({"application_id": app_id, **dscr_result})

    return outputs


def run_dscr_mcp_client(applications: list[dict] = None) -> list[dict]:
    if not DSCR_SERVER_PATH.exists():
        raise FileNotFoundError(f"{DSCR_SERVER_PATH} not found. Run `python dscr_server.py` first to generate it.")
    # Fetched once, BEFORE asyncio.run below (call_mcp_tool runs its own event loop).
    assessment_rate_pct = get_assessment_rate_pct()
    print(f"Assessment rate from rates MCP server: {assessment_rate_pct}%")
    try:
        return asyncio.run(_run_dscr_for_all(applications or load_raw_records(), assessment_rate_pct))
    except BaseException as exc:  # noqa: BLE001
        raise _unwrap_exception_group(exc) from None


def add_calculated_dscr(records: list[dict], dscr_results: list[dict]) -> list[dict]:
    """Copies of `records` with `calculated_dscr` added (None where the DSCR call failed or was skipped)."""
    dscr_by_id = {r["application_id"]: r.get("dscr") for r in dscr_results}
    return [{**record, "calculated_dscr": dscr_by_id.get(record.get("application_id"))} for record in records]


def save_json(data, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    with open(tmp, "w", encoding="utf-8") as f:   # write to a temp file first, then swap in,
        json.dump(data, f, indent=2, ensure_ascii=False)
    tmp.replace(path)                             # so a crash can't leave a half-written file
    print(f"\nSaved {len(data)} records -> {path}")


def load_existing(path: Path) -> list[dict]:
    """Results saved by earlier runs, so a run on N records doesn't drop the others."""
    if path.exists():
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    return []


def merge_by_id(existing: list[dict], new: list[dict]) -> list[dict]:
    """Replace entries with the same application_id, add the rest (earlier order kept)."""
    by_id = {r.get("application_id"): r for r in existing}
    for r in new:
        by_id[r.get("application_id")] = r
    return list(by_id.values())


