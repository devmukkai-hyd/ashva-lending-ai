HIDDEN_FROM_AGENT = {"ground_truth", "proprietor_name", "city", "application_language"}


def _extract_json(text: str) -> str:
    """Pull the JSON object out of the reply, tolerating ```json fences or stray prose."""
    text = (text or "").strip()
    start, end = text.find("{"), text.rfind("}")
    return text[start:end + 1] if start != -1 and end > start else text


def _build_assessment(content: str | None, record: dict, tools_used: list[str], tool_results: dict) -> dict:
    """Combine the LLM's narrative with the authoritative policy result."""
    narrative = AgentNarrative()
    gaps: list[str] = []
    if content is not None:
        try:
            narrative = AgentNarrative.model_validate_json(_extract_json(content))
        except (ValidationError, ValueError) as e:
            gaps.append(f"Agent narrative could not be parsed: {e}")
            narrative.rationale = (content or "")[:500]

    # The policy result never depends on whether the LLM called assign_risk_grade correctly.
    result = tool_results.get("assign_risk_grade") or assess_application(record)
    assessment = RiskAssessment(
        **{k: v for k, v in result.items() if k in RiskAssessment.model_fields and k != "data_gaps"},
        key_risks=narrative.key_risks,
        data_gaps=list(dict.fromkeys(result.get("data_gaps", []) + narrative.data_gaps + gaps)),
        rationale=narrative.rationale,
        tools_used=tools_used,
    )
    return assessment.model_dump()


def _not_assessable(record: dict) -> dict:
    """Intake marked the record Invalid: don't score it, send it back for completion."""
    detail = record.get("reason_description") or "Intake validation failed."
    return RiskAssessment(
        application_id=record.get("application_id") or "<unknown>",
        applicant_id=record.get("applicant_id"),
        decision="borderline",
        risk_band="borderline",
        decision_reasons=[{"code": "INCOMPLETE_APPLICATION",
                           "meaning": "A figure needed to test a standard was not supplied",
                           "is_decline_reason": False, "route": "borderline",
                           "detail": f"Intake validation: {detail}"}],
        data_gaps=[f"Intake validation: {detail}"],
    ).model_dump()


def run_rules(record: dict) -> dict:
    """Same tools and decision as the agent, without an LLM (no rationale)."""
    if not _assessable(record):
        return _not_assessable(record)
    _RECORDS[record["application_id"]] = record
    return _build_assessment(None, record, ["assign_risk_grade"], {})


def _plain(obj):
    """LiteLLM objects or dicts -> plain dicts/lists, without Pydantic's serializer warnings."""
    if isinstance(obj, dict):
        return {k: _plain(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_plain(v) for v in obj]
    if hasattr(obj, "model_dump"):
        return _plain(obj.model_dump(warnings=False))
    if hasattr(obj, "__dict__"):
        return {k: _plain(v) for k, v in vars(obj).items() if not k.startswith("_")}
    return obj


def _assistant_message(message) -> dict:
    """The model's reply as a plain dict for the next request.

    Appending LiteLLM's Message object directly makes Pydantic warn when Gemini's tool calls come back as
    dicts. Each tool call is copied whole, so Gemini's provider_specific_fields (the thought signature
    Gemini 3 needs back with every function call) are kept.
    """
    msg = _plain(message)
    out = {"role": "assistant", "content": msg.get("content")}
    calls = [c for c in (msg.get("tool_calls") or []) if c]
    if calls:
        out["tool_calls"] = [{**c, "type": c.get("type") or "function"} for c in calls]
    for key in ("provider_specific_fields", "thinking_blocks", "reasoning_content"):
        if msg.get(key):
            out[key] = msg[key]
    return out


def run_risk_agent(application: dict, max_steps: int = 3) -> dict:
    """Run the tool-calling loop for ONE application and return a structured assessment."""
    if not _assessable(application):
        return _not_assessable(application)
    if not MODEL:
        raise RuntimeError("LAB_MODEL is not set.")

    app_id = application.get("application_id", "<unknown>")
    _RECORDS[app_id] = application
    agent_view = {k: v for k, v in application.items()
                  if k not in HIDDEN_FROM_AGENT and k not in ("reason_code", "reason_description")}

    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": "Assess this loan application:\n" + json.dumps(agent_view, indent=2, default=str)},
    ]
    tools_used: list[str] = []
    tool_results: dict[str, dict] = {}  # latest SUCCESSFUL result per tool

    for step in range(max_steps):
        last_step = step == max_steps - 1
        response = completion(
            model=MODEL,
            messages=messages,
            tools=TOOL_SCHEMAS,
            # Turn 1: the model calls the tools. Last turn: tools are switched off so it has to answer.
            tool_choice="none" if last_step else "auto",
            api_key=GEMINI_API_KEY,  # litellm's Gemini default env var is GEMINI_API_KEY, not yours
        )
        message = response.choices[0].message
        assistant_turn = _assistant_message(message)
        messages.append(assistant_turn)

        if not assistant_turn.get("tool_calls"):  # no more tool calls -> this is the final answer
            return _build_assessment(assistant_turn.get("content"), application, tools_used, tool_results)

        for call in assistant_turn["tool_calls"]:
            name = call["function"]["name"]
            raw_args = call["function"].get("arguments") or "{}"
            try:
                arguments = json.loads(raw_args) if isinstance(raw_args, str) else dict(raw_args)
            except json.JSONDecodeError:
                result = {"error": "Tool arguments were not valid JSON."}
            else:
                result = execute_tool(name, arguments)
            tools_used.append(name)
            if "error" not in result:
                tool_results[name] = result
            print(f"  [tool] {name}({raw_args}) -> {json.dumps(result, default=str)[:300]}")
            messages.append({
                "role": "tool",
                "tool_call_id": call["id"],
                "name": name,
                "content": json.dumps(result, default=str),
            })

    # Out of steps: still return the policy result, without a narrative.
    out = _build_assessment(None, application, tools_used, tool_results)
    out["data_gaps"].append(f"Agent did not finish within {max_steps} steps; no rationale written.")
    return out


def run_on_records(records: list[dict], limit: int, use_agent: bool) -> list[dict]:
    results = []
    for record in records[:limit]:
        app_id = record.get("application_id", "<unknown>")
        print(f"\n=== {'Risk agent' if use_agent else 'Rules'}: {app_id} ===")
        try:
            assessment = run_risk_agent(record) if use_agent else run_rules(record)
        except Exception as e:  # fail safe: a person looks at it
            err = str(_unwrap_exception_group(e))
            assessment = {"application_id": app_id, "decision": "borderline", "risk_band": "borderline",
                          "routing_reasons": [f"Assessment failed: {err}"], "error": err}
        print(f"  grade {assessment.get('risk_grade')}  DSCR {assessment.get('dscr')}  "
              f"-> {assessment.get('decision')}  {[r['code'] for r in assessment.get('decision_reasons', [])]}")
        results.append(assessment)
    return results


def risk_band(assessment: dict) -> str:
    """approve / borderline / decline (auto_approve is an approve the system may sign alone)."""
    if assessment.get("risk_band"):
        return assessment["risk_band"]
    decision = assessment.get("decision")
    return "approve" if decision in ("approve", "auto_approve") else decision if decision == "decline" else "borderline"


def to_output_record(record: dict, assessment: dict) -> dict:
    """Intake record + lookups + assessment -> the application-record layout."""
    record = _usable_numbers(record)
    applicant_id = record.get("applicant_id")
    try:
        profile = _by_applicant("applicants.json").get(applicant_id) or {}
        bureau = _by_applicant("bureau_reports.json").get(applicant_id) or {}
    except FileNotFoundError:
        profile, bureau = {}, {}

    financials = {
        "annual_revenue_inr": record.get("declared_annual_revenue_inr"),         # declared (intake)
        "ebitda_inr": profile.get("ebitda_inr"),                                  # applicants.json
        "existing_debt_inr": profile.get("existing_debt_inr"),                    # applicants.json
        "existing_annual_debt_service_inr": record.get("existing_annual_debt_service_inr"),
        "current_assets_inr": record.get("current_assets_inr"),
        "current_liabilities_inr": record.get("current_liabilities_inr"),
        "months_operating": profile.get("months_operating"),                      # applicants.json
        "collateral_value_inr": record.get("collateral_value_inr"),
    }
    bureau_score = bureau.get("bureau_score")
    missing = [k for k, v in financials.items() if v is None] + (["bureau_score"] if bureau_score is None else [])

    dscr, floor = assessment.get("dscr"), assessment.get("dscr_floor_applied")
    return {
        "application_id": record.get("application_id"),
        "applicant_id": applicant_id,
        "received_at": record.get("received_at") or record.get("received_on"),
        "business_name": profile.get("business_name") or record.get("business_name"),
        "sector": assessment.get("sector") or profile.get("sector"),
        "requested_amount_inr": record.get("requested_amount_inr"),
        "requested_tenor_months": record.get("requested_tenor_months"),
        "declared_financials": financials,
        "bureau_score": bureau_score,
        OUTCOME_BLOCK: {
            "dscr": dscr,
            "meets_dscr_floor": None if dscr is None or floor is None else dscr >= floor,
            "risk_band": risk_band(assessment),
            "requires_human_signoff": assessment.get("decision") != "auto_approve",
            "approval_authority": (None if assessment.get("decision") == "auto_approve"
                                   else approval_authority(record.get("requested_amount_inr"))),
            "missing_fields": missing,
        },
    }


