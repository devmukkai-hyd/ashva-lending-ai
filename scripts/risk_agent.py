def tool_get_bank_statement(applicant_id: str) -> dict:
    """Analyse every monthly statement on file for the applicant."""
    rows = _statements_by_applicant().get(applicant_id.strip(), [])
    if not rows:
        return {"applicant_id": applicant_id, "months_covered": 0,
                "red_flags": ["No bank statements on file."], "source": "bank_statements.json"}

    inflow = [r["inflow_inr"] for r in rows]
    outflow = [r["outflow_inr"] for r in rows]
    closing = [r["closing_balance_inr"] for r in rows]
    bounced = sum(r["bounced_instruments"] for r in rows)
    bounced_months = sum(r["bounced_instruments"] > 0 for r in rows)
    negative_months = sum(c < 0 for c in closing)
    net = sum(inflow) - sum(outflow)

    flags = []
    if bounced:
        flags.append(f"{bounced} bounced instrument(s) across {bounced_months} month(s).")
    if negative_months:
        flags.append(f"Negative closing balance in {negative_months} of {len(rows)} month(s).")
    if net < 0:
        flags.append(f"Outflows exceeded inflows by INR {-net:,} over the period.")
    if len(rows) < MIN_STATEMENT_MONTHS:
        flags.append(f"Only {len(rows)} month(s) of statements (fewer than {MIN_STATEMENT_MONTHS}).")

    return {
        "applicant_id": applicant_id,
        "months_covered": len(rows),
        "period": f"{rows[0]['month']} to {rows[-1]['month']}",
        "statement_ids": [r["statement_id"] for r in rows],
        "total_inflow_inr": sum(inflow),
        "total_outflow_inr": sum(outflow),
        "net_cash_flow_inr": net,
        "avg_monthly_inflow_inr": round(statistics.mean(inflow)),
        "avg_monthly_outflow_inr": round(statistics.mean(outflow)),
        "avg_closing_balance_inr": round(statistics.mean(closing)),
        "min_closing_balance_inr": min(closing),
        "avg_daily_balance_inr": round(statistics.mean(r["avg_daily_balance_inr"] for r in rows)),
        "bounced_instruments_total": bounced,
        "months_with_bounces": bounced_months,
        "months_negative_closing": negative_months,
        "red_flags": flags,
        "source": "bank_statements.json",
    }


