def _usable_numbers(record: dict) -> dict:
    """Records that failed intake validation can hold text where numbers belong; treat those as not supplied."""
    out = dict(record)
    for k in NUMERIC_INTAKE_FIELDS:
        v = out.get(k)
        if v is None or isinstance(v, (int, float)) and not isinstance(v, bool):
            continue
        try:
            out[k] = float(str(v).replace(",", ""))
        except ValueError:
            out[k] = None
    return out


def _assessable(record: dict) -> bool:
    """Invalid intake is still assessed when it can be identified: a decline outranks a missing figure."""
    return record.get("reason_code") != "Invalid" or bool(record.get("application_id") and record.get("applicant_id"))


def assess_application(record: dict) -> dict:
    """Apply policy limits, the sector policy and the CP-M-882 grid to ONE intake record.

    Every figure comes from the intake record or the lookup files, never from the LLM.
    """
    limits = policy_limits()
    record = _usable_numbers(record)
    app_id = record.get("application_id")
    applicant_id = record.get("applicant_id")
    amount = record.get("requested_amount_inr")
    tenor = record.get("requested_tenor_months")
    reasons: list[dict] = []   # {"code", "route", "detail"}
    gaps: list[str] = []

    def add(code: str, route: str, detail: str):
        reasons.append({"code": code, "route": route, "detail": detail})

    if record.get("reason_code") == "Invalid":   # a figure not supplied (or unusable) -> at least borderline
        add("INCOMPLETE_APPLICATION", "borderline",
            f"Intake validation: {record.get('reason_description') or 'failed'}")

    def lookup(fn, *args):
        try:
            return fn(*args)
        except Exception as e:  # missing row, MCP failure
            gaps.append(str(_unwrap_exception_group(e)))
            return None

    profile = lookup(tool_get_applicant_profile, applicant_id) if applicant_id else None
    bureau = lookup(tool_get_credit_bureau, applicant_id) if applicant_id else None
    bank = tool_get_bank_statement(applicant_id) if applicant_id else {"months_covered": 0, "red_flags": []}

    # Sector: applicants.json is authoritative; purpose keywords only as a fallback.
    sector, from_purpose = (profile or {}).get("sector"), False
    if not sector:
        sector, from_purpose = sector_from_purpose(record.get("purpose")), True
    sector_policy = lookup(tool_get_sector_policy, sector) if sector else None
    # Source of the sector policy applied; flagged when the sector had to be inferred from `purpose`.
    sector_source = None
    if sector_policy:
        sector_source = "sector_policies.json" + (" (sector inferred from purpose, unverified)" if from_purpose else "")
    if not sector:
        gaps.append("Sector unknown: applicant not in applicants.json and purpose doesn't indicate one.")

    # export_receivables_usd = existing_annual_debt_service_inr converted to USD at the rates MCP
    # service's USD_INR rate. It replaces the intake value of the same name.
    fx, usd = None, None
    debt_service_inr = record.get("existing_annual_debt_service_inr")
    if debt_service_inr is not None:
        conv = lookup(tool_interest_currency_calculator, "convert_inr_to_currency",
                      float(debt_service_inr), None, None, "USD")
        if conv:
            fx, usd = conv["inr_per_unit"], conv["amount"]
    else:
        gaps.append("existing_annual_debt_service_inr missing: export_receivables_usd not calculated.")

    # DSCR via MCP, EBITDA joined from applicants.json.
    dscr = None
    if profile and None not in (amount, tenor, record.get("existing_annual_debt_service_inr")):
        result = lookup(tool_calculate_dscr, profile["ebitda_inr"], amount, tenor,
                        record["existing_annual_debt_service_inr"])
        dscr = result.get("dscr") if result else None

    # --- Decline: DSCR < 1.0, bureau < 450, under 24 months operating, grade D2 -----------------
    # --- Borderline: any other standard missed --------------------------------------------------
    sector_floor = (sector_policy or {}).get("dscr_floor")
    floor = max(limits["min_dscr"], sector_floor or 0)    # sector floor, never below the policy minimum
    if dscr is None:
        add("INCOMPLETE_APPLICATION", "borderline", "DSCR could not be calculated.")
    elif dscr < DECLINE_DSCR_BELOW:
        add("DSCR_BELOW_FLOOR", "decline",
            f"DSCR {dscr:.2f} is below {DECLINE_DSCR_BELOW:.2f}: cash flow does not cover debt service.")
    elif dscr < floor:
        add("DSCR_BELOW_FLOOR", "borderline",
            f"DSCR {dscr:.2f} is below the {sector or 'policy'} floor of {floor:.2f}.")

    score = (bureau or {}).get("bureau_score")
    if bureau is None or score is None:
        add("INCOMPLETE_APPLICATION", "borderline", "No bureau report / bureau score.")
    else:
        if score < limits["min_bureau_score"]:
            add("ADVERSE_BUREAU", "decline", f"Bureau score {score} is below {limits['min_bureau_score']}.")
        written_off = bureau.get("written_off_amount_inr") or 0
        if bureau.get("dpd_90_ever") or written_off >= limits["write_off_limit_inr"]:
            detail = "90-day delinquency on record" if bureau.get("dpd_90_ever") else ""
            if written_off >= limits["write_off_limit_inr"]:
                detail = (detail + "; " if detail else "") + f"INR {written_off:,} written off"
            add("PAST_DELINQUENCY", "borderline", detail + ".")

    months = (profile or {}).get("months_operating")
    trade_lines = (bureau or {}).get("active_trade_lines")
    if months is not None and months < limits["min_months_operating"]:
        add("THIN_FILE", "decline", f"{months} months operating (minimum {limits['min_months_operating']}).")
    elif trade_lines == 0:
        # reason_codes.json lists "no active trade line" under THIN_FILE, but policy_limits.json only sets the
        # months-operating minimum, so this one is borderline (a person decides) rather than a bare-minimum decline.
        add("THIN_FILE", "borderline", "No active trade line on the bureau report.")

    leverage = None
    if profile and amount is not None:
        ebitda = profile["ebitda_inr"]
        total_debt = (profile.get("existing_debt_inr") or 0) + amount
        leverage = round(total_debt / ebitda, 2) if ebitda > 0 else None
        if ebitda <= 0 or leverage > limits["max_leverage"]:
            add("LEVERAGE_ABOVE_LIMIT", "borderline",
                f"Debt after the loan is {'not covered by EBITDA' if ebitda <= 0 else f'{leverage:.2f}x EBITDA'} "
                f"(maximum {limits['max_leverage']:.1f}x).")

    current_ratio = None
    ca, cl = record.get("current_assets_inr"), record.get("current_liabilities_inr")
    if ca is not None and cl:
        current_ratio = round(ca / cl, 2)
        if current_ratio < limits["min_current_ratio"]:
            add("LIQUIDITY_BELOW_FLOOR", "borderline",
                f"Current ratio {current_ratio:.2f} is below {limits['min_current_ratio']:.2f}.")
    elif ca is None or cl is None:
        add("INCOMPLETE_APPLICATION", "borderline", "Current assets or liabilities missing.")

    # Declared (intake) vs verified (applicants.json) revenue.
    variance = None
    declared, verified = record.get("declared_annual_revenue_inr"), (profile or {}).get("annual_revenue_inr")
    if declared and verified:
        variance = round(abs(declared - verified) / verified * 100, 1)
        if variance > limits["fraud_hold_pct"]:
            add("FRAUD_HOLD", "borderline",
                f"Declared revenue INR {declared:,} vs verified INR {verified:,} ({variance}% apart, "
                f"over {limits['fraud_hold_pct']}%): hold for fraud review.")
        elif variance > limits["revenue_tolerance_pct"]:
            add("DOC_MISMATCH", "borderline",
                f"Declared revenue INR {declared:,} vs verified INR {verified:,} ({variance}% apart, "
                f"over {limits['revenue_tolerance_pct']}%).")

    # --- Sector policy ------------------------------------------------------------------------
    if sector_policy and sector_policy.get("at_sector_cap"):
        add("SECTOR_CAP", "borderline",
            f"{sector} is at its maximum share of the loan book ({sector_policy['max_exposure_pct']}%); "
            "route to a Senior Credit Reviewer.")

    # --- CP-M-882 grade grid (risk_grades.json) -------------------------------------------------
    grade_row = None
    if dscr is not None and score is not None:
        grade_row = next((g for g in risk_grades()
                          if dscr >= g["min_dscr"] and score >= g["min_bureau_score"]), risk_grades()[-1])
    grade = grade_row["grade"] if grade_row else None

    base_rate = indicative_rate = max_tenor = collateral_pct = collateral_required = None
    if grade_row:
        base_rate = lookup(get_reference_rate, BASE_RATE_NAME)
        indicative_rate = (round(base_rate + grade_row["spread_bps"] / 100, 2) if base_rate is not None
                           else grade_row["indicative_rate_pct"])
        collateral_pct = grade_row["collateral_cover_pct"]
        max_tenor = grade_row["max_tenor_months"]
        if sector_policy:
            max_tenor = min(max_tenor, sector_policy["max_tenor_months"])        # 4.3.1
        if tenor and tenor > max_tenor:                                          # 4.3.2
            add("TENOR_ABOVE_LIMIT", "borderline",
                f"Requested tenor {tenor} months exceeds the permitted {max_tenor} (grade/sector, 4.3.2).")
        if amount is not None:
            collateral_required = round(amount * collateral_pct / 100, 2)       # 4.4.1
            collateral_value = record.get("collateral_value_inr")
            if collateral_pct > 0:
                if collateral_value is None:
                    add("INCOMPLETE_APPLICATION", "borderline",
                        f"Grade {grade} needs {collateral_pct}% collateral cover but no collateral value was given.")
                elif collateral_value < collateral_required:                   # 4.4.2 / 4.4.3
                    add("COLLATERAL_SHORTFALL", "borderline",
                        f"Collateral INR {collateral_value:,} is below the required INR {collateral_required:,.0f} "
                        f"({collateral_pct}% for grade {grade}).")
        if grade in ("C2", "D1"):                                               # 4.5.2
            add("GRADE_REQUIRES_REVIEW", "borderline", f"Grade {grade} is never approved automatically (4.5.2).")
        elif grade == "D2" and not any(r["route"] == "decline" for r in reasons):
            # D2 = fails the D1 minimums; normally already a decline through DSCR < 1.0 or bureau < 450.
            add("DSCR_BELOW_FLOOR", "decline", "Grade D2: below the minimum DSCR and bureau score of every lendable grade.")

    # --- Route ----------------------------------------------------------------------------------
    if not reasons:
        add("APPROVED_STANDARD", "approve", "Meets every underwriting standard.")
    band = max((r["route"] for r in reasons), key=ROUTE_SEVERITY.get)      # decline / borderline / approve

    # Can the system approve it alone? approve + amount <= auto-approval limit + grade C1 or better.
    routing_notes = []
    if band == "approve":
        if amount is None or amount > limits["auto_approve_limit_inr"]:
            routing_notes.append(f"Amount INR {amount:,} is above the INR {limits['auto_approve_limit_inr']:,} "
                                 f"limit for system approval." if amount is not None else "Amount unknown.")
        if not (grade_row and grade_row["auto_approve_allowed"]):            # A1-C1 per risk_grades.json
            routing_notes.append(f"Grade {grade} is not C1 or better.")
        if BANK_FLAGS_BLOCK_AUTO_APPROVE and bank.get("red_flags"):
            routing_notes.append("Bank statement red flags: " + " ".join(bank["red_flags"]))
    auto = band == "approve" and not routing_notes
    decision = "auto_approve" if auto else band
    if not auto:
        routing_notes.append(f"Human sign-off required: {approval_authority(amount) or 'authority unknown (no amount)'}.")

    reasons.sort(key=lambda r: (-ROUTE_SEVERITY[r["route"]], DECLINE_CODES_ORDER.index(r["code"])))
    catalogue = reason_catalogue()

    return {
        "application_id": app_id,
        "applicant_id": applicant_id,
        "sector": sector,
        "sector_source": sector_source,
        "sector_dscr_floor": sector_floor,
        "policy_min_dscr": limits["min_dscr"],
        "dscr_floor_applied": floor,
        "ebitda_inr": (profile or {}).get("ebitda_inr"),
        "dscr": dscr,
        "bureau_score": score,
        "risk_grade": grade,
        "base_rate_pct": base_rate,
        "indicative_rate_pct": indicative_rate,
        "max_tenor_months": max_tenor,
        "collateral_required_pct": collateral_pct,
        "collateral_required_inr": collateral_required,
        "leverage_x": leverage,
        "current_ratio": current_ratio,
        "revenue_variance_pct": variance,
        "export_receivables_usd": usd,
        "usd_inr_rate": fx,
        "bank_statement_summary": bank,
        "decision": decision,
        "decision_reasons": [
            {"code": r["code"], "meaning": catalogue.get(r["code"], {}).get("meaning"),
             "is_decline_reason": catalogue.get(r["code"], {}).get("is_decline_reason"),
             "route": r["route"], "detail": r["detail"]}
            for r in reasons
        ],
        "routing_reasons": routing_notes,
        "risk_band": band,
        "requires_human_signoff": not auto,
        "approval_authority": None if auto else approval_authority(amount),
        "requires_named_signatory": bool(amount and amount > limits["signatory_threshold_inr"]),
        "data_gaps": gaps,
    }


def tool_assign_risk_grade(application_id: str) -> dict:
    record = _RECORDS.get(application_id.strip())
    if record is None:
        raise ValueError(f"Unknown application_id '{application_id}'. Use the id from the application.")
    return assess_application(record)


