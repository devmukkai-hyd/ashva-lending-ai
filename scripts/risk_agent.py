@lru_cache(maxsize=None)
def _load_lookup(name: str):
    path = LOOKUP_DIR / name
    if not path.exists():
        raise FileNotFoundError(f"{path} not found. Put the lookup files there or set WEALTHPILOT_LOOKUP_DIR.")
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


@lru_cache(maxsize=None)
def _by_applicant(name: str) -> dict:
    """applicant_id -> row (applicants.json, bureau_reports.json: one row per applicant)."""
    return {r["applicant_id"]: r for r in _load_lookup(name)}


@lru_cache(maxsize=None)
def _statements_by_applicant() -> dict:
    out: dict[str, list] = {}
    for r in _load_lookup("bank_statements.json"):
        out.setdefault(r["applicant_id"], []).append(r)
    for rows in out.values():
        rows.sort(key=lambda r: r["month"])
    return out


@lru_cache(maxsize=None)
def policy_limits() -> dict:
    return {r["limit"]: r["value"] for r in _load_lookup("policy_limits.json")}


@lru_cache(maxsize=None)
def sector_policies() -> dict:
    return {r["sector"].lower(): r for r in _load_lookup("sector_policies.json")}


@lru_cache(maxsize=None)
def risk_grades() -> list[dict]:
    # Best grade first: CP-M-882 4.1.2 picks the HIGHEST grade whose DSCR AND bureau minimums are met.
    return sorted(_load_lookup("risk_grades.json"), key=lambda g: (-g["min_dscr"], -g["min_bureau_score"]))


@lru_cache(maxsize=None)
def reason_catalogue() -> dict:
    return {r["reason_code"]: r for r in _load_lookup("reason_codes.json")}


