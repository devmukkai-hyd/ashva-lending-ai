def execute_tool(name: str, arguments: dict) -> dict:
    """Run one tool call. Errors are returned to the LLM as data instead of crashing the loop."""
    fn = TOOL_REGISTRY.get(name)
    if fn is None:
        return {"error": f"Unknown tool '{name}'."}
    try:
        return fn(**arguments)
    except Exception as e:  # bad args, missing id, MCP failure, ...
        return {"error": str(_unwrap_exception_group(e))}


